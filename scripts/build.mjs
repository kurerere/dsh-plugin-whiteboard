// Build both runtime artifacts with esbuild.
//
//   lib/index.js   Host face: ESM for Node. Schemastery is inlined (any copy
//                  implements Standard Schema); every other @deepseek-ai/*
//                  import stays external so shared-identity packages
//                  (dsh-scope) resolve to the running installation's copy.
//   lib/client.js  Browser face: the factory form the dsh Web module loader
//                  expects — a classic script calling
//                  window.__ModuleLoader__.load({ id, factory: (require) => … })
//                  with a CommonJS body. Shell platform modules (React,
//                  Cordis, client-store, ui-slots, ui-primitives, …) are
//                  `require`d from the module table, never bundled; every
//                  other dependency (three.js) is bundled in.
//
// This mirrors packages/client/tsdown.client.ts (clientBundle) from the dsh
// monorepo, which is not published for out-of-tree use.

import { build } from 'esbuild'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const manifest = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'))
const id = manifest.name
/** Readable builds while iterating (`WB_DEV=1 pnpm run build`). */
const dev = process.env.WB_DEV === '1'

/** Mirror of packages/client/web/src/platform.ts PLATFORM_MODULES (dsh 0.2.x). */
const PLATFORM_MODULES = [
  'react', 'react/jsx-runtime', 'react-dom', 'react-dom/client', '@deepseek-ai/cordis',
  'zod', '@tanstack/react-virtual',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
]

/**
 * Host face: keep dsh packages external, inline the stateless schema library.
 *
 * `@deepseek-ai/dsh-tools` stays external on purpose. It is not a thin helper —
 * bundling it drags in the tools runtime and its own graph (sandbox, brand, llm,
 * scope) and only moves the problem. The one shared package this face imports is
 * resolved by the running installation, which is also what keeps its brand checks
 * (Session, Agent, Context) on a single module instance.
 */
const hostExternals = {
  name: 'dsh-host-externals',
  setup(b) {
    b.onResolve({ filter: /^@deepseek-ai\// }, (args) => {
      if (/^@deepseek-ai\/(schemastery|cosmokit)(\/|$)/.test(args.path)) return undefined
      return { path: args.path, external: true }
    })
  },
}

/** Browser face: platform modules are external; any other runtime dsh import is a bug. */
const clientExternals = {
  name: 'dsh-client-externals',
  setup(b) {
    b.onResolve({ filter: /^[^./]/ }, (args) => {
      if (PLATFORM_MODULES.includes(args.path)) return { path: args.path, external: true }
      if (args.path.startsWith('@deepseek-ai/')) {
        return { errors: [{ text: `runtime import of ${args.path} is not a shell platform module; use import type or a Cordis service` }] }
      }
      return undefined
    })
  },
}

await mkdir(resolve(root, 'lib'), { recursive: true })

await build({
  absWorkingDir: root,
  entryPoints: ['src/index.ts'],
  outfile: 'lib/index.js',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  plugins: [hostExternals],
  legalComments: 'none',
  logLevel: 'warning',
  banner: { js: `// ${id} ${manifest.version} — Host face (generated by scripts/build.mjs; do not edit)` },
})

const client = await build({
  absWorkingDir: root,
  entryPoints: ['src/client/index.ts'],
  bundle: true,
  write: false,
  platform: 'browser',
  format: 'cjs',
  target: 'es2022',
  jsx: 'automatic',
  minify: !dev,
  loader: { '.css': 'text' },
  plugins: [clientExternals],
  legalComments: 'none',
  logLevel: 'warning',
  define: { 'process.env.NODE_ENV': '"production"' },
})
const body = client.outputFiles[0].text
const wrapped = [
  `// ${id} ${manifest.version} — browser face (generated by scripts/build.mjs; do not edit)`,
  `window.__ModuleLoader__.load({ id: ${JSON.stringify(id)}, factory: (require) => {`,
  'var module = { exports: {} }; var exports = module.exports;',
  body,
  'return module.exports; } });',
  '',
].join('\n')
await writeFile(resolve(root, 'lib/client.js'), wrapped)

console.log(`built lib/index.js and lib/client.js for ${id}@${manifest.version} (${dev ? 'dev' : 'min'})`)
